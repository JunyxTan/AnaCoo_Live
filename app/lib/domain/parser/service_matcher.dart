class ServiceMatch {
  const ServiceMatch({
    required this.rawText,
    this.service,
    this.confidence = 0,
  });

  /// Exactly what the customer wrote, kept for the "couldn't match" chip.
  final String rawText;

  /// Null when nothing scored high enough. The form is then left empty rather
  /// than filled with a guess.
  final ServiceType? service;
  final double confidence;

  bool get matched => service != null;
}

