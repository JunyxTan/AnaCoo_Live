/// Enough evidence to fill the field in: one strong keyword, or two weak ones.
const double _confidenceFloor = 2;

/// Maps free text onto [ServiceType], refusing to guess when the evidence is
/// thin. A low-confidence result keeps [ServiceMatch.rawText] so the UI can
/// show it as an unmatched chip.
ServiceMatch matchService(String rawText) {
  final raw = rawText.trim();
  if (raw.isEmpty) return const ServiceMatch(rawText: '');

  final probe = normaliseForMatching(raw);
  if (probe.isEmpty) return ServiceMatch(rawText: raw);

  for (final entry in _canonicalLabels.entries) {
    for (final label in entry.value) {
      if (normaliseForMatching(label) == probe) {
        return ServiceMatch(rawText: raw, service: entry.key, confidence: 1);
      }
    }
  }

  final scores = <ServiceType, double>{};
  for (final type in ServiceType.values) {
    var score = 0.0;
    for (final word in _strongKeywords[type] ?? const <String>[]) {
      if (_containsTerm(probe, word)) score += 2;
    }
    for (final word in _weakKeywords[type] ?? const <String>[]) {
      if (_containsTerm(probe, word)) score += 1;
    }
    scores[type] = score;
  }

  ServiceType? best;
  var bestScore = 0.0;
  var runnerUp = 0.0;
  scores.forEach((type, score) {
    if (score > bestScore) {
      runnerUp = bestScore;
      bestScore = score;
      best = type;
    } else if (score > runnerUp) {
      runnerUp = score;
    }
  });

  // A tie means two services fit equally well — that is exactly the case where
  // guessing does damage, so bail out and let the tailor pick.
  if (best == null || bestScore < _confidenceFloor || bestScore == runnerUp) {
    return ServiceMatch(rawText: raw, confidence: bestScore / 6);
  }

  final margin = (bestScore - runnerUp) / bestScore;
  return ServiceMatch(
    rawText: raw,
    service: best,
    confidence: (0.5 + margin / 2).clamp(0.0, 1.0),
  );
}

/// CJK has no word boundaries, so those terms match as substrings while Latin
/// terms must sit on a word boundary — otherwise "hem" hits "them".
bool _containsTerm(String haystack, String term) {
  if (term.isEmpty) return false;
  if (term.codeUnitAt(0) > 0x2000) return haystack.contains(term);
  final pattern = RegExp(
    '(?<![a-z0-9])${RegExp.escape(term)}(?![a-z0-9])',
    caseSensitive: false,
  );
  return pattern.hasMatch(haystack);
}
